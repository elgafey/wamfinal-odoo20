# -*- coding: utf-8 -*-
"""Stored record of a bank fees allocation.

One record is created every time the *Bank Fees Allocation* wizard is
confirmed.  It keeps the whole story of the operation: the source journal
items, the amounts, the generated journal entry and the state of the
operation, so that it can be cancelled (and reversed) later on.
"""

from odoo import _, api, fields, models
from odoo.exceptions import UserError
from odoo.tools import SQL


class BankFeesAllocation(models.Model):
    """ Bank Fees Allocation.

    The record is the *history* of one allocation: it is created when the
    wizard is confirmed and it is the object the accountant comes back to
    when they need to undo an operation.

    It inherits ``sequence.mixin`` (the Odoo 20 mechanism used by
    ``account.move`` itself) so that ``name`` gets a readable, sortable
    document number such as ``BFA/2026/00042``.
    """

    _name = 'bank.fees.allocation'
    _inherit = ['sequence.mixin', 'mail.thread']
    _description = 'Bank Fees Allocation'
    _order = 'date desc, id desc'
    _check_company_auto = True

    # The sequence number, e.g. ``BFA/2026/00042``.
    name = fields.Char(
        string='Reference',
        copy=False,
        index='trigram',
        default=lambda self: '/',
        help='Document number of the allocation.',
    )

    date = fields.Date(
        string='Date',
        required=True,
        default=fields.Date.context_today,
        index=True,
    )

    company_id = fields.Many2one(
        comodel_name='res.company',
        string='Company',
        required=True,
        default=lambda self: self.env.company,
        index=True,
    )

    user_id = fields.Many2one(
        comodel_name='res.users',
        string='Done By',
        default=lambda self: self.env.user,
    )

    bank_account_id = fields.Many2one(
        comodel_name='account.account',
        string='Bank Account',
        required=True,
        check_company=True,
        help='Bank account the aggregated settlement was credited to.',
    )

    journal_id = fields.Many2one(
        comodel_name='account.journal',
        string='Journal',
        check_company=True,
        help='Journal of the generated allocation entry.',
    )

    # ------------------------------------------------------------------
    # Amounts
    # ------------------------------------------------------------------
    currency_id = fields.Many2one(
        comodel_name='res.currency',
        string='Currency',
        required=True,
        default=lambda self: self.env.company.currency_id,
    )

    total_amount = fields.Monetary(
        string='Total Amount',
        currency_field='currency_id',
        required=True,
        help='Sum of the balances of the allocated source journal items.',
    )

    net_amount = fields.Monetary(
        string='Net Amount',
        currency_field='currency_id',
        required=True,
        help='Amount actually credited by the bank (total minus fees).',
    )

    fee_amount = fields.Monetary(
        string='Fee Amount',
        currency_field='currency_id',
        required=True,
        help='Bank fees charged on the settlement.',
    )

    # ------------------------------------------------------------------
    # Links
    # ------------------------------------------------------------------
    move_id = fields.Many2one(
        comodel_name='account.move',
        string='Journal Entry',
        copy=False,
        help='First journal entry generated by this allocation.',
    )

    move_ids = fields.Many2many(
        comodel_name='account.move',
        relation='bank_fees_allocation_move_rel',
        column1='allocation_id',
        column2='move_id',
        string='Journal Entries',
        copy=False,
        help='Every journal entry generated by this allocation: one per '
             'branch of the allocated journal items.',
    )

    line_ids = fields.Many2many(
        comodel_name='account.move.line',
        string='Allocated Journal Items',
        relation='bank_fees_allocation_line_rel',
        column1='allocation_id',
        column2='line_id',
        help='Source journal items that were allocated.',
    )

    state = fields.Selection(
        selection=[
            ('done', 'Done'),
            ('cancelled', 'Cancelled'),
        ],
        string='Status',
        default='done',
        required=True,
        copy=False,
        index=True,
    )

    # ------------------------------------------------------------------
    # Technical / computed
    # ------------------------------------------------------------------
    account_ids = fields.Many2many(
        comodel_name='account.account',
        string='Allocation Accounts',
        compute='_compute_account_ids',
        store=False,
        help='Allocation accounts the source journal items belong to.',
    )

    source_account_ids = fields.Many2many(
        comodel_name='account.account',
        string='Source Accounts',
        compute='_compute_account_ids',
        store=False,
        help='Accounts (branches) of the source journal items.',
    )

    branch_ids = fields.Many2many(
        comodel_name='branch.branch',
        relation='bank_fees_allocation_branch_rel',
        column1='allocation_id',
        column2='branch_id',
        string='Branches',
        compute='_compute_branch_ids',
        store=True,
        help='Branches of the allocated source journal items.',
    )

    fee_ratio = fields.Float(
        string='Fee Ratio (%)',
        compute='_compute_fee_ratio',
        store=False,
        help='Fees expressed as a percentage of the allocated total.',
    )

    currency_note = fields.Char(compute='_compute_currency_note')

    # ------------------------------------------------------------------
    # Computes
    # ------------------------------------------------------------------
    @api.depends('line_ids', 'line_ids.account_id')
    def _compute_account_ids(self):
        """ Expose the accounts of the source items. """
        for record in self:
            accounts = record.line_ids.mapped('account_id')
            record.account_ids = accounts
            record.source_account_ids = accounts

    @api.depends('line_ids', 'line_ids.branch_id')
    def _compute_branch_ids(self):
        """ Expose the branches of the source items.

        The field is stored so that the history can be filtered, grouped
        and pivoted on the branch.
        """
        for record in self:
            record.branch_ids = record.line_ids.mapped('branch_id')

    @api.depends('fee_amount', 'total_amount')
    def _compute_fee_ratio(self):
        """ Fees as a percentage of the allocated total. """
        for record in self:
            if record.total_amount:
                record.fee_ratio = (record.fee_amount / record.total_amount) * 100.0
            else:
                record.fee_ratio = 0.0

    @api.depends('currency_id')
    def _compute_currency_note(self):
        for record in self:
            record.currency_note = record.currency_id.name or ''

    # ------------------------------------------------------------------
    # Sequence
    # ------------------------------------------------------------------
    @api.model_create_multi
    def create(self, vals_list):
        """ Give the new records their sequence number.

        The number is taken from the series of the company, and it is
        never moved afterwards: the Odoo 20 ``sequence.mixin`` mechanism
        takes care of the locking, so two allocations created at the same
        time never share a number.
        """
        records = super().create(vals_list)
        for record in records:
            if record.name and record.name != '/':
                continue
            if not record.date:
                continue
            record._set_next_sequence()
        return records

    def _get_last_sequence_domain(self, relaxed=False):
        """ Only take the previous number of the same company **and** of the
        same year into account.

        The series restarts every year: the numbers of the year 2026 and
        the ones of the year 2027 are two independent series.
        """
        self.ensure_one()
        record_date = self.date or fields.Date.context_today(self)
        return SQL(
            "company_id = %s AND sequence_prefix = %s",
            self.company_id.id,
            'BFA/%04d/' % record_date.year,
        )

    def _must_check_constrains_date_sequence(self):
        """ The number is given to the record when it is created.

        The core check refuses a record whose number does not match its
        date: it makes sense for the documents whose number is editable
        (a sales invoice), but not here, where the number is assigned
        once and for all by the sequence.
        """
        return False

    def _get_starting_sequence(self):
        """ First number of the series.

        The format is the one understood by ``sequence.mixin``:
        ``BFA/<year>/<number>``.  Because the series restarts every year,
        the year of the record is used.
        """
        self.ensure_one()
        record_date = self.date or fields.Date.context_today(self)
        return 'BFA/%04d/0000' % record_date.year

    # ------------------------------------------------------------------
    # Actions
    # ------------------------------------------------------------------
    def action_view_move(self):
        """ Open the generated journal entries.

        A single entry (one branch) is opened in its form; when the
        allocation spans several branches, the list of its entries is shown.
        """
        self.ensure_one()
        moves = self.move_ids or self.move_id
        if len(moves) > 1:
            return {
                'type': 'ir.actions.act_window',
                'name': _('Journal Entries'),
                'res_model': 'account.move',
                'view_mode': 'list,form',
                'domain': [('id', 'in', moves.ids)],
                'context': {'create': False},
            }
        return {
            'type': 'ir.actions.act_window',
            'name': _('Journal Entry'),
            'res_model': 'account.move',
            'res_id': moves.id,
            'view_mode': 'form',
            'target': 'current',
        }

    def action_view_lines(self):
        """ Open the source journal items that were allocated. """
        self.ensure_one()
        return {
            'type': 'ir.actions.act_window',
            'name': _('Allocated Journal Items'),
            'res_model': 'account.move.line',
            'view_mode': 'list,form',
            'domain': [('id', 'in', self.line_ids.ids)],
            'context': {'create': False},
        }

    def action_cancel(self):
        """ Unreconcile and reverse the generated journal entries.

        The reversal is done with Odoo's own ``account.move`` reversal
        (``_reverse_moves`` + ``action_post``) so that the reversal entries
        carry the same accounts, amounts, branches and analytic
        distributions as the original ones.

        The source journal items are freed: the reconciliation links are
        removed before the reversal, exactly like Odoo does when the user
        unreconciles a journal entry.
        """
        for record in self:
            if record.state == 'cancelled':
                raise UserError(_("This allocation has already been cancelled."))
            moves = record.move_ids or record.move_id
            if not moves:
                raise UserError(_("This allocation has no journal entry to cancel."))
            if all(move.state == 'cancel' for move in moves):
                raise UserError(_("The journal entry of this allocation is already cancelled."))
        self._unreconcile_allocation()
        self._reverse_allocation_moves()
        self.write({'state': 'cancelled'})
        return True

    def _unreconcile_allocation(self):
        """ Remove the reconciliation links of the allocation.

        The links are removed through ``account.move.line.remove_move_reconcile()``,
        the very same method Odoo's own *Unreconcile* button uses.
        """
        self.ensure_one()
        moves = self.move_ids or self.move_id
        lines = moves.line_ids | self.line_ids
        # Only the lines of the source items and of the generated entries
        # take part in the reconciliation: the partner entries of the source
        # documents must stay untouched.
        linked = lines.filtered(lambda line: line.reconciled or line.full_reconcile_id)
        if linked:
            linked.remove_move_reconcile()

    def _reverse_allocation_moves(self):
        """ Post the reversal of every generated journal entry.

        The reversals are created by Odoo's own ``_reverse_moves()`` (the
        very method the *Reverse* button of a journal entry uses), so the
        reversal entries carry the same accounts, amounts, branches and
        analytic distributions as the original ones.
        """
        self.ensure_one()
        moves = self.move_ids or self.move_id
        reversals = self.env['account.move']
        for move in moves:
            reversal = move._reverse_moves([{'date': fields.Date.context_today(self)}])
            reversal.action_post()
            reversals |= reversal
            self.message_post(body=_(
                "The journal entry %s has been reversed by %s.", move.name, reversal.name
            ))
        return reversals

    # ------------------------------------------------------------------
    # Constraints
    # ------------------------------------------------------------------
    @api.constrains('net_amount', 'fee_amount', 'total_amount')
    def _check_amounts(self):
        """ The net amount plus the fees must equal the allocated total. """
        for record in self:
            if record.currency_id.compare_amounts(
                record.net_amount + record.fee_amount, record.total_amount
            ) != 0:
                raise UserError(_(
                    "On allocation %s, the net amount plus the fees (%s) must equal "
                    "the total amount (%s).",
                    record.name,
                    record.currency_id.format(record.net_amount + record.fee_amount),
                    record.currency_id.format(record.total_amount),
                ))
            if record.currency_id.compare_amounts(record.fee_amount, 0.0) < 0:
                raise UserError(_("On allocation %s, the fee amount cannot be negative.", record.name))
            if record.currency_id.compare_amounts(record.net_amount, 0.0) < 0:
                raise UserError(_("On allocation %s, the net amount cannot be negative.", record.name))

    # ------------------------------------------------------------------
    # Display
    # ------------------------------------------------------------------
    def name_get(self):
        """ Show the reference with the date, like a document number. """
        result = []
        for record in self:
            name = record.name or _('New')
            if name == '/':
                name = _('New')
            result.append((record.id, f"{name} ({record.date})" if record.date else name))
        return result
